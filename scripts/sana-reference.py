"""Regenerate tiny SANA numerical oracles: torch 2.8.0, diffusers 0.33.1, transformers 4.51.3.

No Python is used by DeepJ. These fixtures independently verify the Java port.
"""
from pathlib import Path
import json
import torch
from safetensors.torch import save_file
from diffusers import SanaTransformer2DModel, AutoencoderDC, SCMScheduler
from transformers import Gemma2Config, Gemma2Model

ROOT = Path(__file__).resolve().parents[1] / "src/test/resources/sana"
torch.manual_seed(681)
torch.set_num_threads(1)
reference = {}


def store(name, model, inputs, output):
    path = ROOT / name
    path.mkdir(parents=True, exist_ok=True)
    save_file({k: v.contiguous() for k, v in model.state_dict().items()}, path / "model.safetensors")
    if name == "gemma":
        model.config.to_json_file(path / "config.json")
    else:
        model.save_config(path)
    reference.update({name + "." + k: v.contiguous() for k, v in inputs.items()})
    reference[name + ".output"] = output.contiguous()


with torch.no_grad():
    gemma = Gemma2Model(Gemma2Config(
        vocab_size=32, hidden_size=16, intermediate_size=24, num_hidden_layers=2,
        num_attention_heads=2, num_key_value_heads=1, head_dim=8,
        max_position_embeddings=64, sliding_window=4, query_pre_attn_scalar=8,
        attn_logit_softcapping=50, rms_norm_eps=1e-6,
        hidden_activation="gelu_pytorch_tanh", attn_implementation="eager")).eval()
    ids = torch.tensor([[2, 9, 4, 11, 13, 18, 0]])
    mask = torch.tensor([[1, 1, 1, 1, 1, 1, 0]])
    store("gemma", gemma, {"tokens": ids.float(), "mask": mask.float()},
          gemma(ids, attention_mask=mask).last_hidden_state)

    reference["gemma.output_bf16"] = gemma.to(torch.bfloat16)(
        ids, attention_mask=mask).last_hidden_state.float().contiguous()

    sana = SanaTransformer2DModel(in_channels=4, out_channels=4,
        num_attention_heads=2, attention_head_dim=8, num_layers=2,
        num_cross_attention_heads=2, cross_attention_head_dim=8,
        cross_attention_dim=16, caption_channels=16, mlp_ratio=2.5,
        sample_size=4, guidance_embeds=True, qk_norm="rms_norm_across_heads").eval()
    latent = torch.randn(1, 4, 4, 4)
    text = torch.randn(1, 7, 16)
    mask = torch.tensor([[1, 1, 1, 1, 1, 0, 0]])
    result = sana(latent, encoder_hidden_states=text, encoder_attention_mask=mask,
                  timestep=torch.tensor([0.6]), guidance=torch.tensor([0.45])).sample
    store("transformer", sana, {"input": latent, "text": text, "mask": mask.float()}, result)

    vae = AutoencoderDC(in_channels=3, latent_channels=4, attention_head_dim=4,
        encoder_block_types=("ResBlock", "EfficientViTBlock"),
        decoder_block_types=("ResBlock", "EfficientViTBlock"),
        encoder_block_out_channels=(8, 16), decoder_block_out_channels=(8, 16),
        encoder_layers_per_block=(1, 1), decoder_layers_per_block=(1, 1),
        encoder_qkv_multiscales=((), (3,)), decoder_qkv_multiscales=((), (3,)),
        upsample_block_type="interpolate", downsample_block_type="Conv").eval()
    for size in (2, 4):
        latent = torch.randn(1, 4, size, size)
        reference[f"vae{size}.input"] = latent
        reference[f"vae{size}.output"] = vae.decode(latent).sample.contiguous()
    store("vae", vae, {}, reference["vae2.output"])
    # Same group/padding/layout as the new convolution, with independent PyTorch gradients.
    x = torch.randn(1, 4, 4, 5).requires_grad_()
    w = torch.randn(6, 2, 3, 3).requires_grad_()
    b = torch.randn(6).requires_grad_()
with torch.enable_grad():
    y = torch.nn.functional.conv2d(x, w, b, padding=1, groups=2)
    y.square().sum().backward()
for name, value in {"input": x, "weight": w, "bias": b, "output": y,
                    "dx": x.grad, "dw": w.grad, "db": b.grad}.items():
    reference["conv." + name] = value.detach().contiguous()
# Scheduler outputs are generated by diffusers, including its stochastic step.
for steps in (1, 2, 3, 4):
    scheduler = SCMScheduler(prediction_type="trigflow", sigma_data=0.5)
    scheduler.set_timesteps(steps, max_timesteps=1.57080,
                           intermediate_timesteps=1.3 if steps == 2 else None)
    sample = torch.randn(1, 4, 2, 2) * 0.5
    for index, angle in enumerate(scheduler.timesteps[:-1]):
        time = torch.sin(angle) / (torch.cos(angle) + torch.sin(angle))
        factor = (time.square() + (1 - time).square()).sqrt()
        model_input = sample / 0.5 * factor
        prediction = torch.randn_like(sample)
        noise_prediction = ((1 - 2 * time) * model_input
                            + (1 - 2 * time + 2 * time.square()) * prediction) / factor * 0.5
        generator = torch.Generator().manual_seed(928 + index)
        noise = torch.randn(sample.shape, generator=torch.Generator().manual_seed(928 + index))
        next_sample, denoised = scheduler.step(noise_prediction, angle, sample,
                                               generator=generator, return_dict=False)
        prefix = f"scm{steps}_{index}."
        reference.update({prefix + key: value for key, value in {
            "latent": sample, "input": model_input, "prediction": prediction,
            "noise": noise, "denoised": denoised, "next": next_sample}.items()})
        sample = next_sample
save_file({k: v.clone() for k, v in reference.items()}, ROOT / "model.safetensors")
print("Saved independent reference fixtures to", ROOT)

